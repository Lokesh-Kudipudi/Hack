"""Two compact, single-default comparison charts for the 10-slide presentation.

Source: results/model_comparison.md, generated by eval.nab_compare.
Run: python -m eval.presentation_charts
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import matplotlib.pyplot as plt
from matplotlib.ticker import FixedLocator, FuncFormatter

from eval.data import REPO_ROOT

SOURCE = REPO_ROOT / "results" / "model_comparison.md"
FIGURES = REPO_ROOT / "results" / "figures"
INK = "#24313b"
MUTED = "#77818a"
ACCENT = "#255f72"
GRID = "#dce1e5"


@dataclass(frozen=True)
class Model:
    name: str
    f1: float
    precision: float | None
    recall: float
    us: float | None

    @property
    def ours(self) -> bool:
        return self.name == "Sentinel — engine default (ours)"


def read_models(path: Path = SOURCE) -> list[Model]:
    models = []
    for line in path.read_text().splitlines():
        if not line.startswith("| "):
            continue
        fields = [field.strip().replace("**", "") for field in line.strip().strip("|").split("|")]
        if len(fields) != 10 or not fields[0].isdigit():
            continue
        name = fields[1]
        if name.startswith("Sentinel — NAB operating point"):
            continue
        precision = None if fields[3] == "—" else float(fields[3])
        try:
            runtime = float(fields[9])
        except ValueError:
            runtime = None
        models.append(Model(name, float(fields[2]), precision, float(fields[4]), runtime))
    if sum(model.ours for model in models) != 1:
        raise ValueError("Expected exactly one current Sentinel default")
    return models


def short_name(name: str) -> str:
    aliases = {
        "Sentinel — engine default (ours)": "Sentinel",
        "Windowed Gaussian (NAB)": "Windowed Gaussian",
        "Random (NAB)": "Random",
        "Null (NAB)": "Null",
        "earthgecko Skyline": "Skyline",
        "Relative Entropy": "Rel. Entropy",
        "Random Cut Forest": "RCF",
        "Twitter ADVec": "Twitter ADVec",
        "Numenta HTM": "Numenta HTM",
        "Numenta TM": "Numenta TM",
        "Etsy Skyline": "Etsy Skyline",
    }
    return aliases.get(name, name)


def style() -> None:
    plt.rcParams.update({
        "font.family": "DejaVu Sans", "font.size": 9,
        "axes.edgecolor": GRID, "axes.labelcolor": INK, "text.color": INK,
        "xtick.color": INK, "ytick.color": INK,
        "axes.spines.top": False, "axes.spines.right": False,
        "figure.facecolor": "white", "axes.facecolor": "white",
        "savefig.facecolor": "white",
    })


def event_f1_vs_time(models: list[Model], path: Path) -> None:
    fig = plt.figure(figsize=(8.4, 5.2), layout="constrained")
    grid = fig.add_gridspec(1, 2, width_ratios=[1.6, 1], wspace=0.08)
    ax = fig.add_subplot(grid[0, 0])
    side = fig.add_subplot(grid[0, 1])

    for number, model in enumerate(models, 1):
        if model.us is None:
            continue
        ax.scatter(model.us, model.f1, s=160 if model.ours else 110,
                   color=ACCENT if model.ours else MUTED, zorder=3)
        ax.annotate(str(number), (model.us, model.f1), ha="center", va="center",
                    fontsize=7.4, weight="bold", color="white")
    ax.set_xscale("symlog", linthresh=0.1)
    ax.set_xlim(-0.06, 4500)
    ax.set_ylim(-0.035, 0.78)
    ax.xaxis.set_major_locator(FixedLocator([0, 0.1, 1, 10, 100, 1000]))
    ax.xaxis.set_major_formatter(FuncFormatter(lambda value, _: f"{value:g}"))
    ax.set_xlabel("Inference time (µs / point; compressed scale)")
    ax.set_ylabel("Event-F1")
    ax.grid(color=GRID, alpha=0.65, linewidth=0.7)

    side.axis("off")
    side.text(0.02, 0.99, "Model key", fontsize=9, weight="bold", va="top")
    side.text(0.98, 0.99, "F1", fontsize=7.6, weight="bold", ha="right", va="top")
    for i, model in enumerate(models):
        y = 0.915 - i * 0.052
        name = short_name(model.name) + (" *" if model.us is None else "")
        side.text(0.02, y, f"{i + 1:>2}  {name}", fontsize=7.5,
                  weight="bold" if model.ours else "normal",
                  color=ACCENT if model.ours else INK, va="top")
        side.text(0.98, y, f"{model.f1:.3f}", fontsize=7.5, ha="right", va="top")
    side.text(0.02, 0.025, "* local runtime unavailable", fontsize=7.2,
              color=MUTED, va="bottom")
    fig.suptitle("Event-F1 vs inference time", x=0.035, ha="left", fontsize=14, weight="bold")
    fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)


def precision_vs_recall(models: list[Model], path: Path) -> None:
    fig = plt.figure(figsize=(8.4, 5.2), layout="constrained")
    grid = fig.add_gridspec(1, 2, width_ratios=[1.6, 1], wspace=0.08)
    ax = fig.add_subplot(grid[0, 0])
    side = fig.add_subplot(grid[0, 1])
    plotted = [model for model in models if model.precision is not None]
    for number, model in enumerate(plotted, 1):
        ax.scatter(model.recall, model.precision, s=160 if model.ours else 105,
                   color=ACCENT if model.ours else MUTED, zorder=3)
    # Keep exact point locations. If several sit almost on top of each other,
    # place one combined identifier next to them so no model disappears.
    groups: list[list[int]] = []
    for i, model in enumerate(plotted):
        for group in groups:
            first = plotted[group[0]]
            if abs(model.recall - first.recall) <= 0.012 and abs(model.precision - first.precision) <= 0.012:
                group.append(i)
                break
        else:
            groups.append([i])
    for group in groups:
        if len(group) == 1:
            i = group[0]
            model = plotted[i]
            ax.annotate(str(i + 1), (model.recall, model.precision), ha="center", va="center",
                        fontsize=7.2, weight="bold", color="white")
        else:
            x = sum(plotted[i].recall for i in group) / len(group)
            y = sum(plotted[i].precision for i in group) / len(group)
            label = "/".join(str(i + 1) for i in group)
            ax.annotate(label, (x, y), xytext=(5, -11),
                        textcoords="offset points", fontsize=7.2, color=INK,
                        bbox={"facecolor": "white", "edgecolor": "none", "pad": 0.6})
    ax.set_xlim(0.30, 1.0)
    ax.set_ylim(0.0, 0.82)
    ax.set_xticks([0.4, 0.6, 0.8, 1.0])
    ax.set_yticks([0.0, 0.2, 0.4, 0.6, 0.8])
    ax.set_xlabel("Recall →")
    ax.set_ylabel("Precision →")
    ax.grid(color=GRID, alpha=0.65, linewidth=0.7)

    side.axis("off")
    side.text(0.02, 0.99, "Model key", fontsize=9, weight="bold", va="top")
    for i, model in enumerate(plotted):
        y = 0.915 - i * 0.052
        side.text(0.02, y, f"{i + 1:>2}  {short_name(model.name)}", fontsize=7.5,
                  weight="bold" if model.ours else "normal",
                  color=ACCENT if model.ours else INK, va="top")
    side.text(0.02, 0.025, "Null: precision undefined", fontsize=7.2,
              color=MUTED, va="bottom")
    fig.suptitle("Precision vs recall", x=0.035, ha="left", fontsize=14, weight="bold")
    fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    style()
    models = read_models()
    FIGURES.mkdir(parents=True, exist_ok=True)
    event_f1_vs_time(models, FIGURES / "event_f1_vs_inference_time.png")
    precision_vs_recall(models, FIGURES / "precision_vs_recall_models.png")
    print(f"Plotted {len(models)} models, including one Sentinel default")


if __name__ == "__main__":
    main()
