"""Two compact, two-panel comparison charts for the 10-slide presentation.

Source: docs/results/model_performance_comparison.md, generated by eval.nab_compare.
Run: python -m eval.presentation_charts
"""
from __future__ import annotations

from math import log10
from dataclasses import dataclass
from pathlib import Path

import matplotlib.pyplot as plt

from eval.data import REPO_ROOT

SOURCE = REPO_ROOT / "docs" / "results" / "model_performance_comparison.md"
FIGURES = REPO_ROOT / "results" / "figures"
INK = "#24313b"
MUTED = "#77818a"
ACCENT = "#255f72"
GRID = "#dce1e5"


@dataclass(frozen=True)
class Model:
    name: str
    f1: float
    precision: float | None
    recall: float
    us: float | None

    @property
    def ours(self) -> bool:
        return self.name == "Sentinel — engine default (ours)"


def read_models(path: Path = SOURCE) -> list[Model]:
    models = []
    for line in path.read_text().splitlines():
        if not line.startswith("| "):
            continue
        fields = [field.strip().replace("**", "") for field in line.strip().strip("|").split("|")]
        if len(fields) != 10 or not fields[0].isdigit():
            continue
        name = fields[1]
        if name.startswith("Sentinel — NAB operating point"):
            continue
        precision = None if fields[3] == "—" else float(fields[3])
        try:
            runtime = float(fields[9])
        except ValueError:
            runtime = None
        models.append(Model(name, float(fields[2]), precision, float(fields[4]), runtime))
    if sum(model.ours for model in models) != 1:
        raise ValueError("Expected exactly one current Sentinel default")
    return models


def short_name(name: str) -> str:
    aliases = {
        "Sentinel — engine default (ours)": "Sentinel",
        "Windowed Gaussian (NAB)": "Windowed Gaussian",
        "Random (NAB)": "Random",
        "Null (NAB)": "Null",
        "earthgecko Skyline": "Skyline",
        "Relative Entropy": "Rel. Entropy",
        "Random Cut Forest": "RCF",
        "Twitter ADVec": "Twitter ADVec",
        "Numenta HTM": "Numenta HTM",
        "Numenta TM": "Numenta TM",
        "Etsy Skyline": "Etsy Skyline",
    }
    return aliases.get(name, name)


def style() -> None:
    plt.rcParams.update({
        "font.family": "DejaVu Sans", "font.size": 8,
        "axes.edgecolor": GRID, "axes.labelcolor": INK, "text.color": INK,
        "xtick.color": INK, "ytick.color": INK,
        "axes.spines.top": False, "axes.spines.right": False,
        "figure.facecolor": "white", "axes.facecolor": "white",
        "savefig.facecolor": "white",
    })


def two_panel(models: list[Model], left_name: str, right_name: str, path: Path) -> None:
    fig, (left, right) = plt.subplots(1, 2, figsize=(8.4, 5.4), sharey=True)
    fig.subplots_adjust(left=0.30, right=0.975, top=0.86, bottom=0.13, wspace=0.18)
    rows = list(range(len(models)))
    colours = [ACCENT if model.ours else MUTED for model in models]

    def value(model: Model, metric: str) -> float | None:
        return {"Event-F1": model.f1, "Inference time": model.us,
                "Precision": model.precision, "Recall": model.recall}[metric]

    for ax, metric in ((left, left_name), (right, right_name)):
        raw = [value(model, metric) for model in models]
        # Compress the large latency range so the 2.7 µs Sentinel bar remains visible.
        plotted = [log10(1 + number) if metric == "Inference time" and number is not None
                   else number or 0 for number in raw]
        ax.barh(rows, plotted, height=0.64, color=colours, zorder=2)
        ax.set_title(metric, fontsize=10, weight="bold", pad=10)
        ax.grid(axis="x", color=GRID, linewidth=0.7, zorder=0)
        ax.set_axisbelow(True)
        if metric == "Inference time":
            ticks = [0, 1, 10, 100, 1000]
            ax.set_xticks([log10(1 + tick) for tick in ticks], [str(tick) for tick in ticks])
            ax.set_xlim(0, log10(1 + 4500))
            ax.set_xlabel("µs / point (compressed scale)", fontsize=7.7)
        else:
            ax.set_xlim(0, 0.93 if metric == "Event-F1" else 1.08)
            ax.set_xticks([0, 0.25, 0.5, 0.75] if metric == "Event-F1"
                          else [0, 0.25, 0.5, 0.75, 1.0])
        for row, (number, length) in enumerate(zip(raw, plotted)):
            label = "—" if number is None else (f"{number:g}" if metric == "Inference time"
                                                    else f"{number:.3f}")
            ax.text(max(length + 0.025, 0.04), row, label, va="center", fontsize=7.0,
                    color=ACCENT if models[row].ours else INK,
                    weight="bold" if models[row].ours else "normal")
    left.set_yticks(rows, [short_name(model.name) for model in models], fontsize=7.8)
    left.tick_params(axis="y", length=0, pad=7, labelleft=True)
    right.tick_params(axis="y", length=0, labelleft=False)
    left.invert_yaxis()
    fig.suptitle(f"{left_name} and {right_name.lower()} by model", x=0.04, ha="left",
                 fontsize=13, weight="bold")
    fig.savefig(path, dpi=220)
    plt.close(fig)


def event_f1_vs_time(models: list[Model], path: Path) -> None:
    two_panel(models, "Event-F1", "Inference time", path)


def precision_vs_recall(models: list[Model], path: Path) -> None:
    two_panel(models, "Precision", "Recall", path)


def main() -> None:
    style()
    models = read_models()
    FIGURES.mkdir(parents=True, exist_ok=True)
    event_f1_vs_time(models, FIGURES / "event_f1_vs_inference_time.png")
    precision_vs_recall(models, FIGURES / "precision_vs_recall_models.png")
    print(f"Plotted {len(models)} models, including one Sentinel default")


if __name__ == "__main__":
    main()
