"""One leaderboard across models: event-F1 / precision / recall (our scorer) + measured inference time.

Published NAB detectors: event metrics from NAB's stored per-point scores (data/NAB/results/<det>/) at NAB's own
standard-profile threshold (config/thresholds.json); every crossing above the threshold starts an event (no merging
or cooldown). Inference time from the latest `python -m eval.nab_runtime` record (same streams, same machine).
Sentinel / baselines: latest full-corpus runs from results/runs/.

    python -m eval.nab_runtime     # first, for the timing column
    python -m eval.nab_compare

Writes results/model_comparison.md and results/figures/model_comparison.png.
"""
from __future__ import annotations

import json
from typing import Dict, List, Optional

import numpy as np
import pandas as pd

from eval import scorer
from eval.data import list_files, load_windows, windows_path
from eval.leaderboard import load_runs
from eval.nab_runtime import NOT_RUNNABLE
from eval.nab_score import NAB_DIR
from eval.run import REPO_ROOT

NAMES = {"ARTime": "ARTime", "numenta": "Numenta HTM", "contextOSE": "CAD OSE", "htmjava": "HTM Java",
         "numentaTM": "Numenta TM", "earthgeckoSkyline": "earthgecko Skyline", "knncad": "KNN CAD",
         "relativeEntropy": "Relative Entropy", "randomCutForest": "Random Cut Forest", "twitterADVec": "Twitter ADVec",
         "windowedGaussian": "Windowed Gaussian (NAB)", "skyline": "Etsy Skyline", "bayesChangePt": "Bayesian Changepoint",
         "random": "Random (NAB)", "expose": "EXPoSE", "null": "Null (NAB)"}
OURS = [(("sentinel", "engine default (final)"), "Sentinel — engine default (ours, submitted)"),
        (("sentinel", "NAB operating point (final)"), "Sentinel — NAB operating point (ours)")]


def published_event_metrics() -> Dict[str, Dict]:
    pub = json.loads((NAB_DIR / "results" / "final_results.json").read_text())
    thr = json.loads((NAB_DIR / "config" / "thresholds.json").read_text())
    windows = load_windows(windows_path())
    files = list_files()
    out = {}
    for det in pub:
        t = thr.get(det, {}).get("standard", {}).get("threshold")
        if t is None:
            continue
        fss = []
        for f in files:
            p = NAB_DIR / "results" / det / f.category / f"{det}_{f.name}"
            if not p.is_file():
                break
            df = pd.read_csv(p)
            a = df["anomaly_score"].values >= t
            starts = a & ~np.r_[False, a[:-1]]
            fss.append(scorer.score_file(df["timestamp"], starts, windows.get(f.key, []), f.key, f.category))
        else:
            out[det] = {**scorer.metrics(fss), "nab": pub[det]["standard"], "threshold": t}
    return out


def build() -> List[Dict]:
    runs = load_runs()
    rt = [r for r in runs if r.get("kind") == "nab_runtime"]
    timing = {r["detector"]: r["us_per_point_mean"] for r in rt[-1]["results"]} if rt else {}
    rows = []
    for det, m in published_event_metrics().items():
        rows.append({"model": NAMES.get(det, det), "f1": m["f1"], "precision": m["precision"], "recall": m["recall"],
                     "tp": m["tp"], "fp": m["fp"], "fn": m["fn"], "nab": m["nab"], "us": timing.get(det),
                     "note": NOT_RUNNABLE.get(det), "ours": False})
    latest = {(r["detector"], r.get("tag")): r for r in runs if "overall" in r and not r.get("categories")}
    for key, lab in OURS:
        r = latest.get(key)
        if r:
            o = r["overall"]
            rows.append({"model": lab, "f1": o["f1"], "precision": o["precision"], "recall": o["recall"],
                         "tp": o["tp"], "fp": o["fp"], "fn": o["fn"], "nab": r["nab"]["standard"]["score"],
                         "us": timing.get("Sentinel (engine default)") if "default" in lab else r["runtime"]["us_per_point"],
                         "note": None, "ours": True})
    return sorted(rows, key=lambda r: -(r["f1"] or 0))


def _f(v, nd=3):
    return "—" if v is None else f"{v:.{nd}f}"


def render(rows: List[Dict], held_out: Optional[float]) -> str:
    lines = ["# Model comparison: event-F1, precision, recall, inference time", "",
             "Generated by `python -m eval.nab_compare`. Event metrics with our scorer (AGENTS.md §5) on the full NAB "
             "corpus (58 files, 116 windows). Published detectors: NAB's stored scores at NAB's own standard-profile "
             "threshold, each threshold crossing = one event (no merging/cooldown — their thresholds were tuned for "
             "the NAB score, so treat their event-F1 as a lower bound). Inference time: µs per point measured on the "
             "same machine and streams (`results/runtime_comparison.md`); \"not runnable\" = needs a stack we cannot "
             "run here.", "",
             "| # | Model | Event-F1 | Precision | Recall | TP | FP | FN | NAB std | µs/point |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        us = f"{r['us']:.1f}" if r["us"] is not None else f"not runnable ({r['note']})" if r["note"] else "—"
        name = f"**{r['model']}**" if r["ours"] else r["model"]
        lines.append(f"| {i} | {name} | **{_f(r['f1'])}** | {_f(r['precision'])} | {_f(r['recall'])} | {r['tp']} | "
                     f"{r['fp']} | {r['fn']} | {_f(r['nab'], 1)} | {us} |")
    if held_out is not None:
        lines += ["", f"Sentinel's engine default was tuned on this corpus; its leave-one-category-out held-out "
                      f"event-F1 is **{held_out:.3f}** (pooled)."]
    lines.append("")
    return "\n".join(lines)


def plot(rows: List[Dict], path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    pts = [r for r in rows if r["us"] is not None and r["us"] > 0.5]
    fig, ax = plt.subplots(figsize=(8, 5))
    for r in pts:
        col = "#d93025" if r["ours"] else "#5f6368"
        ax.scatter(r["us"], r["f1"], s=90 if r["ours"] else 45, color=col, zorder=3)
        ax.annotate(r["model"].replace(" (ours, submitted)", "").replace(" (ours)", ""), (r["us"], r["f1"]),
                    textcoords="offset points", xytext=(6, 4), fontsize=7, color=col)
    ax.set_xscale("log")
    ax.set_xlabel("Inference time, µs per point (log scale, same machine)")
    ax.set_ylabel("Event-F1 (full NAB corpus)")
    ax.set_title("Accuracy vs speed: NAB detectors run locally vs Sentinel")
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(alpha=0.25)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main() -> List[Dict]:
    rows = build()
    tunes = [r for r in load_runs() if r.get("kind") == "tune" and r.get("tag") == "loco-recall2"]
    held = tunes[-1]["loco"]["pooled_held_out"]["f1"] if tunes else None
    (REPO_ROOT / "results" / "model_comparison.md").write_text(render(rows, held))
    plot(rows, REPO_ROOT / "results" / "figures" / "model_comparison.png")
    print("wrote results/model_comparison.md, results/figures/model_comparison.png")
    return rows


if __name__ == "__main__":
    main()
