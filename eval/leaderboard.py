"""Collect results/runs/*.json into results/leaderboard.md.

    python -m eval.leaderboard
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, List, Optional, Sequence

from eval.run import RUNS_DIR
from eval.data import REPO_ROOT

OUT = REPO_ROOT / "results" / "leaderboard.md"
# NAB standard-profile scores from data/NAB/results/final_results.json, for reference
NAB_PUBLISHED = [("ARTime", 74.9), ("Numenta HTM", 70.1), ("contextOSE", 69.9), ("earthgeckoSkyline", 58.2),
                 ("randomCutForest", 51.7), ("windowedGaussian", 39.6), ("random", 16.8), ("null", 0.0)]


def load_runs(runs_dir: Path = RUNS_DIR) -> List[Dict]:
    runs = []
    for p in sorted(runs_dir.glob("*.json")):
        try:
            runs.append(json.loads(p.read_text()))
        except json.JSONDecodeError:
            print(f"skipping unreadable {p.name}")
    return runs


def _f(v, nd=3) -> str:
    return "—" if v is None else f"{v:.{nd}f}"


def _name(r: Dict) -> str:
    return r["detector"] + (" (local stand-in)" if r.get("sentinel_source") == "local-untracked" else "")


def _key(r: Dict):
    f1 = r["overall"]["f1"]
    return -(f1 if f1 is not None else -1)


def render(runs: Sequence[Dict]) -> str:
    benches = [r for r in runs if r.get("kind") == "benchmark"]
    runs = [r for r in runs if "overall" in r]
    full = [r for r in runs if not r.get("categories")]
    partial = [r for r in runs if r.get("categories")]
    lines = ["# Leaderboard", "",
             "Generated by `python -m eval.leaderboard` from `results/runs/*.json`. "
             "Event metrics per AGENTS.md §5 (micro over corpus, probation excluded). "
             "NAB std = official standard-profile score on per-point scores (threshold optimised on the corpus); "
             "NAB starts = same scorer fed 1 at predicted event starts, 0 elsewhere.", ""]

    def table(rs: Sequence[Dict]) -> None:
        lines.append("| Run | Detector | Tag | Event-F1 | P | R | TP | FP | FN | Delay med (pts) | Delay med (frac) | NAB std | NAB starts | µs/pt | sha |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        for r in sorted(rs, key=_key):
            o, rt = r["overall"], r.get("runtime", {})
            lines.append(
                f"| {r['run_id'][:15]} | {_name(r)} | {r.get('tag', '')} | **{_f(o['f1'])}** | "
                f"{_f(o['precision'])} | {_f(o['recall'])} | {o['tp']} | {o['fp']} | {o['fn']} | "
                f"{_f(o['delay_points_median'], 1)} | {_f(o['delay_fraction_median'], 2)} | "
                f"{_f(r.get('nab', {}).get('standard', {}).get('score'), 1)} | "
                f"{_f(r.get('nab_events', {}).get('score'), 1)} | {_f(rt.get('us_per_point'), 1)} | "
                f"{r.get('git_sha', '')} |")
        lines.append("")

    lines += ["## Full corpus", ""]
    table(full)

    if full:
        top = sorted(full, key=_key)[:6]
        cats = sorted({c for r in top for c in r["per_category"]})
        lines += ["## Event-F1 per category (top runs)", "",
                  "| Run | Detector | " + " | ".join(cats) + " |",
                  "|---|---|" + "---|" * len(cats)]
        for r in top:
            cells = [_f(r["per_category"].get(c, {}).get("f1")) for c in cats]
            lines.append(f"| {r['run_id'][:15]} | {_name(r)} [{r.get('tag', '')}] | " + " | ".join(cells) + " |")
        lines.append("")

    if partial:
        lines += ["## Partial-corpus runs", ""]
        table(partial)

    if benches:
        b = benches[-1]
        lines += [f"## Runtime benchmark ({b['created']}, {b['machine']}, Python {b['python']}, single core)", "",
                  "| Detector | mean µs/pt | p50 | p99 | max | points/s |", "|---|---|---|---|---|---|"]
        for r in b["results"]:
            name = r["detector"] + (" (local stand-in)" if r.get("sentinel_source") == "local-untracked" else "")
            lines.append(f"| {name} | {r['us_per_point_mean']:.2f} | {r['us_per_point_p50']:.2f} | "
                         f"{r['us_per_point_p99']:.2f} | {r['us_per_point_max']:.0f} | {r['points_per_sec']:,.0f} |")
        lines.append("")

    lines += ["## Published NAB leaderboard (standard profile)", "",
              "| Detector | NAB std |", "|---|---|"]
    lines += [f"| {n} | {s} |" for n, s in NAB_PUBLISHED]
    lines.append("")
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> None:
    runs = load_runs()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(runs))
    print(f"wrote {OUT.relative_to(REPO_ROOT)} ({len(runs)} runs)")


if __name__ == "__main__":
    main()
