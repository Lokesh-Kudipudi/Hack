"""L17: why are windows missed, and why are detections late?

For every GT window (probation excluded) under the given config:
  - TP: delay as fraction of the window, and how early *any* detector alarmed inside the window
    (probe run with all 6 detectors, per-detector SPOT alarms read individually).
  - FN, classified:
      suppressed   the engine flagged ANOMALOUS points inside the window but no event started
                   (cooldown / still inside an earlier event / debounce)
      other_det    no alarm from the config's detectors, but a detector outside the config alarmed
      weak         no detector alarmed anywhere in the window

    python -m eval.miss_analysis [--config cfg.json]

Writes docs/results/missed_anomaly_analysis.md and results/figures/miss_analysis.png.
"""
from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path
from statistics import median
from typing import Dict, List, Optional, Sequence

from eval.data import REPO_ROOT, iter_corpus, probation_length, window_indices
from eval.run import sentinel_config

PROBE = {"detectors": ["robust_z", "last_w", "lagged_residual", "var_ratio", "seasonal", "cusum"],
         "fusion": "max", "vote_k": 1}
NAMES = ["RobustZ", "LastW", "LaggedResidual", "VarRatio", "Seasonal", "CUSUM"]


def trace(cfg: dict, df) -> Dict[str, list]:
    """Stream df through Sentinel; per point: label, event start, set of detectors whose SPOT alarm fired."""
    from sentinel.pipeline import Sentinel
    s = Sentinel(n_total=len(df), config=sentinel_config(cfg))
    labels, starts, alarms = [], [], []
    for t, x in zip(df["timestamp"].tolist(), df["value"].tolist()):
        r = s.update(t, x)
        labels.append(r.label == "ANOMALOUS")
        starts.append(r.is_event_start)
        alarms.append({k for k, v in getattr(s, "_alarms", {}).items() if v})
    return {"anom": labels, "start": starts, "alarms": alarms}


def analyse(config: dict) -> Dict:
    rows = []
    for info, df, wins in iter_corpus():
        if not wins:
            continue
        p = probation_length(len(df))
        main, probe = trace(config, df), trace(PROBE, df)
        for i, j in window_indices(df["timestamp"], wins):
            if j < p:
                continue
            centre = (i + j) // 2  # NAB windows are centred on the labelled anomaly point
            i = max(i, p)
            width = j - i + 1
            starts = [k for k in range(i, j + 1) if main["start"][k]]
            first_probe = next((k for k in range(i, j + 1) if probe["alarms"][k]), None)
            probe_dets = sorted({d for k in range(i, j + 1) for d in probe["alarms"][k]})
            row = {"file": info.key, "category": info.category, "start": i, "end": j, "width": width,
                   "probe_detectors": probe_dets,
                   "probe_first_frac": None if first_probe is None else (first_probe - i) / width}
            if starts:
                row.update(status="TP", delay_frac=(starts[0] - i) / width, from_label=starts[0] - centre,
                           gain_frac=None if first_probe is None else (starts[0] - first_probe) / width)
            else:
                in_cfg = {d for k in range(i, j + 1) for d in main["alarms"][k]}
                if any(main["anom"][i:j + 1]):
                    reason = "suppressed"
                elif probe_dets and not in_cfg:
                    reason = "other_det"
                else:
                    reason = "weak"
                row.update(status="FN", reason=reason)
            rows.append(row)
    return {"config": config, "windows": rows}


def _pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "—"


def render(res: Dict) -> str:
    rows = res["windows"]
    tp = [r for r in rows if r["status"] == "TP"]
    fn = [r for r in rows if r["status"] == "FN"]
    reasons = Counter(r["reason"] for r in fn)
    lines = ["# Missed anomaly analysis", "",
             "> **About this report:** Examines labelled windows missed by the current Sentinel default and reports detection delay for the windows it finds.", "",
             f"Config: `{json.dumps(res['config']) or '{}'}` (empty = engine defaults). Probe = all 6 detectors, "
             "MAX fusion, each detector's SPOT alarm read individually. Generated by `python -m eval.miss_analysis`.", "",
             f"**{len(rows)} scorable windows: {len(tp)} detected, {len(fn)} missed.**", "",
             "## Why windows are missed", "",
             "| Reason | Windows | Share of misses | Meaning |", "|---|---|---|---|"]
    meaning = {"suppressed": "engine flagged ANOMALOUS inside the window but no event started (cooldown / earlier event / debounce)",
               "other_det": "the config's detectors stayed silent, but another detector alarmed",
               "weak": "no detector alarmed anywhere in the window"}
    for k in ("suppressed", "other_det", "weak"):
        lines.append(f"| {k} | {reasons[k]} | {_pct(reasons[k], len(fn))} | {meaning[k]} |")
    by_cat = defaultdict(Counter)
    for r in rows:
        by_cat[r["category"]][r["status"] if r["status"] == "TP" else r["reason"]] += 1
    lines += ["", "| Category | TP | suppressed | other_det | weak |", "|---|---|---|---|---|"]
    for c, cnt in sorted(by_cat.items()):
        lines.append(f"| {c} | {cnt['TP']} | {cnt['suppressed']} | {cnt['other_det']} | {cnt['weak']} |")
    det_rescue = Counter(d for r in fn if r["reason"] == "other_det" for d in r["probe_detectors"])
    lines += ["", "Detectors that alarmed inside `other_det` misses (a window can count for several):", "",
              "| Detector | Windows |", "|---|---|"]
    lines += [f"| {d} | {n} |" for d, n in det_rescue.most_common()]
    d = [r["delay_frac"] for r in tp]
    g = [r["gain_frac"] for r in tp if r["gain_frac"] is not None]
    pf = [r["probe_first_frac"] for r in tp if r["probe_first_frac"] is not None]
    lines += ["", "## Detection delay (detected windows)", "",
              f"- Median delay: **{median(d):.2f}** of the window width (mean {sum(d) / len(d):.2f})." if d else "- No TPs.",
              f"- Earliest alarm of *any* detector inside the same windows: median {median(pf):.2f} of the window." if pf else "",
              f"- Potential gain if the first alarm became the event start: median {median(g):.2f} of the window "
              f"({sum(1 for x in g if x > 0.05)} of {len(g)} windows could start > 5% earlier)." if g else "",
              (f"- Relative to the **labelled anomaly point** (window centre): median {median([r['from_label'] for r in tp]):+.0f} "
               f"points; {sum(1 for r in tp if r['from_label'] <= 0)} of {len(tp)} detections are at or before it, "
               f"{sum(1 for r in tp if 0 < r['from_label'] <= 10)} within 10 points after it. NAB windows start well before "
               "the labelled point, so a ~0.5 window fraction means detection at the anomaly itself.") if tp else "",
              f"- Detected in the first quarter of the window: {sum(1 for x in d if x < 0.25)} / {len(d)}; "
              f"before the labelled anomaly (window centre): {sum(1 for x in d if x < 0.5)} / {len(d)}.", "",
              "## Missed windows", "", "| File | Window (idx) | Width | Reason | Probe detectors |", "|---|---|---|---|---|"]
    for r in fn:
        lines.append(f"| {r['file']} | {r['start']}–{r['end']} | {r['width']} | {r['reason']} | "
                     f"{', '.join(r['probe_detectors']) or '—'} |")
    lines.append("")
    return "\n".join(lines)


def plot(res: Dict, path: Path) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    rows = res["windows"]
    fn = Counter(r["reason"] for r in rows if r["status"] == "FN")
    d = [r["delay_frac"] for r in rows if r["status"] == "TP"]
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(10, 3.4))
    keys = ["suppressed", "other_det", "weak"]
    a1.bar(keys, [fn[k] for k in keys], color=["#e8710a", "#7e57c2", "#9aa0a6"])
    a1.set_title(f"Why {sum(fn.values())} windows are missed")
    a2.hist(d, bins=20, range=(0, 1), color="#1a73e8")
    a2.axvline(0.5, color="#202124", ls=":", lw=1)
    a2.text(0.51, a2.get_ylim()[1] * 0.9, "labelled anomaly", fontsize=7)
    a2.set_title("Detection delay (fraction of window)")
    for a in (a1, a2):
        a.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)


def main(argv: Optional[Sequence[str]] = None) -> Dict:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", help="Sentinel overrides (JSON or path); default: engine defaults")
    ap.add_argument("--out", default=str(REPO_ROOT / "docs" / "results" / "missed_anomaly_analysis.md"))
    args = ap.parse_args(argv)
    cfg = {}
    if args.config:
        p = Path(args.config)
        cfg = json.loads(p.read_text() if p.is_file() else args.config)
    res = analyse(cfg)
    Path(args.out).write_text(render(res))
    plot(res, REPO_ROOT / "results" / "figures" / "miss_analysis.png")
    fn = Counter(r["reason"] for r in res["windows"] if r["status"] == "FN")
    print(f"{len(res['windows'])} windows; misses: {dict(fn)}; wrote {args.out}")
    return res


if __name__ == "__main__":
    main()
